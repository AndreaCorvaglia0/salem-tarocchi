// Reading engine tools.
//   --registry                      regenerate src/data/reading/registry.js from voices/*.js
//   --lint [--stubs]                validate every voice file
//   --sample N [--seed S] [--spread ppf|single|celtic] [--ambito x --forma y] [--ref "del campo"] [--stubs]
//   --stats N [same options]        repetition and length report
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const voicesDir = path.join(root, 'src/data/reading/voices');
const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(`--${name}`); return i < 0 ? def : args[i + 1]; };
const flag = (name) => args.includes(`--${name}`);
const files = () => readdirSync(voicesDir).filter((f) => f.endsWith('.js')).sort();

const writeRegistry = () => {
  const names = files().map((f) => ({ f, v: `v_${f.replace(/\.js$/, '').replace(/\W/g, '_')}` }));
  const body = [
    '// GENERATED by `node scripts/readings.mjs --registry`. Do not edit by hand.',
    '// Explicit imports (no import.meta.glob: node tests cannot use it). Ids starting with "_" are test stubs.',
    ...names.map(({ f, v }) => `import ${v} from './voices/${f}';`),
    '',
    `const ALL = [${names.map((n) => n.v).join(', ')}];`,
    'const byId = (list) => Object.fromEntries(list.map((v) => [v.id, v]));',
    "export const VOICES = byId(ALL.filter((v) => !v.id.startsWith('_')));",
    "export const STUBS = byId(ALL.filter((v) => v.id.startsWith('_')));",
    '',
  ].join('\n');
  writeFileSync(path.join(root, 'src/data/reading/registry.js'), body);
  console.log(`registry.js: ${names.length} voice files`);
};

if (flag('registry')) { writeRegistry(); process.exit(0); }

const R = await import('../src/reading/index.js');
const { CARD } = await import('../src/data/cards.base.js');
if (flag('stubs')) R.useStubs(true);
const name = (id) => CARD[id]?.name ?? id;

if (flag('lint')) {
  let bad = 0;
  for (const f of files()) {
    const v = (await import(pathToFileURL(path.join(voicesDir, f)).href)).default;
    const problems = R.validateVoice(v);
    if (v?.id && f !== `${v.id}.js` && !f.startsWith('_stub')) problems.push(`file name does not match id "${v.id}"`);
    if (problems.length && (flag('stubs') || !f.startsWith('_'))) { bad++; console.log(`${f}: ${problems.length} problem(s)`); problems.forEach((p) => console.log(`  ${p}`)); }
  }
  console.log(bad ? `${bad} file(s) with problems` : 'all voices pass');
  process.exit(bad ? 1 : 0);
}

const pool = R.voiceIds();
const spread = opt('spread', 'ppf');
const seed = Number(opt('seed', 1));
const rng = R.seeded(seed);
const randomOf = (list) => list[Math.floor(rng() * list.length)];
const makeOne = () => {
  const question = R.makeQuestion({
    ambito: opt('ambito') ?? randomOf(R.AMBITI), forma: opt('forma') ?? randomOf(R.FORME),
    ref: opt('ref') ? { di: opt('ref') } : undefined,
  });
  const need = { single: 1, ppf: 3, celtic: 10 }[spread];
  if (pool.length < need) { console.error(`Only ${pool.length} voice(s) available, ${need} needed for "${spread}". Try --stubs.`); process.exit(1); }
  const cards = R.drawCards(spread, { rng, pool });
  const plan = R.plan(question, spread, cards);
  return { question, cards, plan, said: R.say(plan, { rng, usedClosings }) };
};
const usedClosings = new Set(); // shared, so two consecutive readings never end the same way
const wordCount = (s) => s.split(/\s+/).length;

if (flag('sample')) {
  for (let i = 0; i < Number(opt('sample', 3)); i++) {
    const { question, cards, plan, said } = makeOne();
    console.log(`--- ${i + 1}. ${question.ambito} / ${question.forma} (${spread}) -> ${plan.verdict.code} (${plan.verdict.score.toFixed(2)})`);
    console.log(cards.map((c) => `${c.pos}: ${name(c.card)}${c.rev ? ' (rovesciata)' : ''}`).join(' | '));
    console.log(said.full);
    if (said.missing.length) console.log(`MISSING: ${JSON.stringify(said.missing)}`);
    if (flag('play')) { // the questions she is asked, card by card, then the final answer
      plan.steps.forEach((st, k) => {
        console.log(`  [${st.pos}] ${name(st.card)}${st.rev ? ' (rovesciata)' : ''} — che idea porta?`);
        for (const a of R.recall(plan, k, { rng, pool, verso: flag('verso') })) console.log(`     ${a.ok ? '(x)' : '( )'} ${a.text}`);
        console.log(`      e qui (${st.role}, ${question.ambito}) che cosa vuol dire?`);
        for (const a of R.alternatives(plan, k, { rng, pool, verso: flag('verso') })) console.log(`     ${a.ok ? '(x)' : '( )'} ${a.text}`);
      });
      console.log('  Quindi, che cosa rispondi?');
      for (const c of R.verdictChoices(plan, { rng })) console.log(`     ${c.ok ? '(x)' : '( )'} ${c.text}`);
    }
    console.log('');
  }
}

if (flag('stats')) {
  const n = Number(opt('stats', 1000));
  let missing = 0; let sameLead = 0; let total = 0; let max = 0;
  const leads = {};
  for (let i = 0; i < n; i++) {
    const { said } = makeOne();
    missing += said.missing.length;
    const used = said.parts.map((p) => p.lead).filter(Boolean);
    if (new Set(used).size < used.length) sameLead++;
    used.forEach((l) => { leads[l] = (leads[l] ?? 0) + 1; });
    const w = wordCount(said.full);
    total += w; max = Math.max(max, w);
  }
  console.log(`readings: ${n}\nmissing lines: ${missing}\nreadings with a repeated lead-in: ${sameLead}`);
  console.log(`words per reading: average ${(total / n).toFixed(1)}, max ${max}`);
  console.log('most used lead-ins:');
  Object.entries(leads).sort((a, b) => b[1] - a[1]).slice(0, 8).forEach(([l, c]) => console.log(`  ${c}  ${l}`));
}
